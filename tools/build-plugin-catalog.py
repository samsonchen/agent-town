"""Generate plugin/hooks/catalog.ts from catalog/roles.json and catalog/task-types.json.

The town-link plugin cannot read files outside its own folder once installed
from the marketplace, and a hooks module can only import .ts/.js files, so the
IDs and rules it needs are copied into a TypeScript module. Run this whenever
catalog/*.json changes:

    python3 tools/build-plugin-catalog.py

Standard library only. `--check` exits 1 when the generated file is out of date.
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "plugin", "hooks", "catalog.ts")


def build():
    with open(os.path.join(ROOT, "catalog", "roles.json")) as fh:
        roles = json.load(fh)
    with open(os.path.join(ROOT, "catalog", "task-types.json")) as fh:
        tasks = json.load(fh)

    staff = [r["id"] for r in roles["roles"] if not r.get("background")]
    background = [r["id"] for r in roles["roles"] if r.get("background")]
    rules = {
        r["id"]: r["rules"]["words"]
        for r in roles["roles"]
        if r.get("background") and r.get("rules", {}).get("words")
    }
    order = [rid for rid in roles["backgroundRuleOrder"] if rid in rules]
    task_types = [t["id"] for t in tasks["taskTypes"]]

    def js(v):
        return json.dumps(v, ensure_ascii=False)

    lines = [
        "// Generated by tools/build-plugin-catalog.py from catalog/*.json. Do not edit.",
        "",
        f"export const STAFF_ROLES: readonly string[] = {js(staff)}",
        f"export const STAFF_FALLBACK = {js(roles['fallback'])}",
        f"export const BACKGROUND_ROLES: readonly string[] = {js(background)}",
        f"export const BACKGROUND_FALLBACK = {js(roles['backgroundFallback'])}",
        "/** Shell-command word rules, checked in this order. */",
        "export const BACKGROUND_RULES: readonly (readonly [string, readonly string[]])[] = ["
    ]
    for rid in order:
        lines.append(f"  [{js(rid)}, {js(rules[rid])}],")
    lines += [
        "]",
        f"export const TASK_TYPES: readonly string[] = {js(task_types)}",
        f"export const TASK_FALLBACK = {js(tasks['fallback'])}",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="Generate plugin/hooks/catalog.ts")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        try:
            with open(OUT) as fh:
                same = fh.read() == text
        except OSError:
            same = False
        print("catalog.ts is up to date" if same else "catalog.ts is out of date")
        sys.exit(0 if same else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
